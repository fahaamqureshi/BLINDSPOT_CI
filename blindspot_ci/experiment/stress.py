"""Stress variants: Muse Image edits a labeled photo into a harder condition.

The edit prompt forbids moving objects, so the source box is inherited. That is an assumption, not
a measurement: every variant is labeled GENERATED and its box is marked as not re-verified. A person
must confirm that the yellow box still sits on the tag in the trace. Variants are never mixed into
the real dataset.
"""
from __future__ import annotations

import io
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from PIL import Image

from blindspot_ci.budget import BudgetGuard
from blindspot_ci.experiment.cases import (
    DATASETS,
    Dataset,
    image_path,
    sha256_file,
)
from blindspot_ci.fsutil import FILE_LOCK, atomic_write_text
from blindspot_ci.providers.meta_extras import IMAGE_COST_USD

KEEP = ("Keep every object in exactly the same position, size and shape. Do not add, remove, move "
        "or recolor anything. Only change the lighting or camera effect described.")
EDITS = {
    "low_light": "Make this photo much darker, as if lit by one dim lamp in a dark room. " + KEEP,
    "glare": "Add a strong bright light glare and reflection across part of the scene, like a "
             "flashlight shining on the surface, without covering the objects. " + KEEP,
    "motion_blur": "Add mild camera motion blur to the whole photo, as if the camera shook. " + KEEP,
}
MAX_VARIANTS_PER_CALL = 6
MIME = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg"}


def generate_variants(source: Dataset, edits: list[str], image_adapter: Any, budget: BudgetGuard,
                      case_ids: list[str] | None = None, datasets: Path = DATASETS) -> list[dict[str, Any]]:
    """Make one variant per (visible source case, edit). Returns the new manifest entries."""
    unknown = [e for e in edits if e not in EDITS]
    if unknown:
        raise ValueError(f"unknown edit {unknown}; choose from {sorted(EDITS)}")
    chosen = [c for c in source.cases.values()
              if c.visibility == "visible" and (case_ids is None or c.id in case_ids)]
    if not chosen or not edits:
        raise ValueError("no visible source cases or no edits selected")
    jobs = [(case, edit) for case in chosen for edit in edits]
    if len(jobs) > MAX_VARIANTS_PER_CALL:
        raise ValueError(f"{len(jobs)} variants requested; the limit is {MAX_VARIANTS_PER_CALL} per call "
                         f"(about ${IMAGE_COST_USD:.2f} each)")
    out_dir = datasets / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    entries: list[dict[str, Any]] = []
    for case, edit in jobs:
        path = image_path(case, datasets)
        budget.reserve(IMAGE_COST_USD)
        try:
            raw = image_adapter.edit(path.read_bytes(), MIME[path.suffix.lower()], EDITS[edit])
            entries.append(_store_variant(case, edit, raw, path, out_dir, image_adapter))
        except Exception as exc:
            exc.partial_entries = list(entries)  # variants already paid for, so the caller can keep them
            raise
    return entries


def _store_variant(case: Any, edit: str, raw: bytes, path: Path, out_dir: Path, image_adapter: Any) -> dict[str, Any]:
    with Image.open(io.BytesIO(raw)) as edited:
        with Image.open(path) as original:
            size = original.size
        edited = edited.convert("RGB")
        if edited.size != size:  # the model may change resolution; the box needs the source size
            edited = edited.resize(size, Image.LANCZOS)
        case_id = f"{case.id}_{edit}"
        target = out_dir / f"{case_id}.png"
        edited.save(target, "PNG")
    return {
        "id": case_id, "title": f"{case.title} ({edit.replace('_', ' ')}, generated)",
        "image": f"generated/{case_id}.png", "condition": edit, "concept": case.concept,
        "ground_truth": {"visibility": "visible", "bbox": list(case.ground_truth_box)},
        "note": "GENERATED by Muse Image. Box inherited from the source photo, not re-verified.",
        "label_provenance": {"annotator": "inherited", "labeled_at": datetime.now(timezone.utc).isoformat(),
                             "source_case": case.id, "generator": image_adapter.model,
                             "box_status": "inherited_from_source_not_reverified",
                             "source_label": case.label_provenance},
        "image_sha256": sha256_file(target)}


def write_manifest(entries: list[dict[str, Any]], source: Dataset, datasets: Path = DATASETS,
                   name: str = "generated") -> Path:
    """Merge new variants into <name>_manifest.json (a newer entry wins on the same id)."""
    kinds = {
        "generated": ("GENERATED_STRESS_VARIANTS_NOT_REAL_PHOTOS",
                      "GENERATED by Muse Image; boxes inherited from the source and not re-verified"),
        "corrupted": ("MEASURED_CORRUPTIONS_OF_LABELED_PHOTOS",
                      "deterministic corruptions of labeled photos; pixels not moved, so labels are exact")}
    kind, status = kinds[name]
    path = datasets / f"{name}_manifest.json"
    with FILE_LOCK:
        return _merge_manifest(path, kind, status, entries, source, name)


def _merge_manifest(path: Path, kind: str, status: str, entries: list[dict[str, Any]], source: Dataset,
                    name: str) -> Path:
    existing: dict[str, Any] = {}
    if path.is_file():
        existing = {c["id"]: c for c in json.loads(path.read_text(encoding="utf-8"))["cases"]}
    existing.update({e["id"]: e for e in entries})
    atomic_write_text(path, json.dumps({
        "dataset_id": f"{name}-from-{source.id}", "type": kind, "annotation_status": status,
        "source_dataset_type": source.kind, "generated_at": datetime.now(timezone.utc).isoformat(),
        "cases": list(existing.values())}, indent=2))
    return path
